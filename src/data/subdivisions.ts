const DEFAULT_LABEL = "State / Province";

const DEFAULT_SUBDIVISIONS: readonly string[] = Object.freeze([
  "Capital Region",
  "Central Region",
  "North Region",
  "South Region",
  "East Region",
  "West Region",
]);

// One shared instance: returning a fresh [] per call would give every
// render a new array identity and defeat the callers' useMemo.

/** The subdivisions of one country, or default regions for unlisted countries, or [] when no country is selected. */
export function subdivisionsFor(countryCode: string | null | undefined): readonly string[] {
  if (!countryCode) return NONE;
  const key = countryCode.trim().toUpperCase();
  return SUBDIVISIONS[key] ?? DEFAULT_SUBDIVISIONS;
}

/**
 * Keeps a saved state only when it belongs to the country now selected.
 */
export function keepSubdivisionIfValid(
  countryCode: string | null | undefined,
  value: string | null | undefined,
): string {
  const saved = (value ?? "").trim();
  if (!saved) return "";
  const list = subdivisionsFor(countryCode);
  return list.includes(saved) ? saved : "";
}

/** True when a country is selected so the state field is a dropdown combobox. */
export function hasSubdivisions(countryCode: string | null | undefined): boolean {
  return Boolean(countryCode && countryCode.trim().length > 0);
}

/** Field label for the country, e.g. "Prefecture" for Japan. */
export function subdivisionLabel(countryCode: string | null | undefined): string {
  if (!countryCode) return DEFAULT_LABEL;
  return LABELS[countryCode.trim().toUpperCase()] ?? DEFAULT_LABEL;
}
